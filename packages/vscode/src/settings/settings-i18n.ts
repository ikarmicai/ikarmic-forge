/** The entries of `SETTINGS_STRINGS` whose translation differs from the English text. */
export function settingsDictionary(translate: (english: string) => string): Record<string, string> {
  const dict: Record<string, string> = {};
  for (const english of SETTINGS_STRINGS) {
    const localized = translate(english);
    if (localized && localized !== english) dict[english] = localized;
  }
  return dict;
}
